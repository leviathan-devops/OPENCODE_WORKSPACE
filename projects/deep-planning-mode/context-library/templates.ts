function estimateTotalTime(data: PlanData): string {
  let totalMinutes = 0;
  
  for (const step of data.steps) {
    const match = step.time.match(/(\d+)/);
    if (match) {
      const num = parseInt(match[1], 10);
      if (step.time.includes('hour') || step.time.includes('h')) {
        totalMinutes += num * 60;
      } else if (step.time.includes('day')) {
        totalMinutes += num * 8 * 60;
      } else {
        totalMinutes += num;
      }
    }
  }
  
  if (totalMinutes < 60) {
    return `${totalMinutes}min`;
  } else if (totalMinutes < 8 * 60) {
    return `${Math.round(totalMinutes / 60)}h`;
  } else {
    return `${Math.round(totalMinutes / 8 / 60)}d`;
  }
}

function detectCycles(dependencies: Dependency[]): string[][] {
  const cycles: string[][] = [];
  const visited = new Set<string>();
  const recursionStack = new Set<string>();
  
  function dfs(nodeId: string, path: string[]): boolean {
    visited.add(nodeId);
    recursionStack.add(nodeId);
    path.push(nodeId);
    
    const node = dependencies.find(d => d.id === nodeId);
    if (node) {
      for (const parent of node.dependsOn) {
        if (!visited.has(parent)) {
          if (dfs(parent, [...path])) {
            return true;
          }
        } else if (recursionStack.has(parent)) {
          // Found cycle
          const cycleStart = path.indexOf(parent);
          if (cycleStart !== -1) {
            cycles.push(path.slice(cycleStart));
          } else {
            cycles.push([...path, parent]);
          }
          return true;
        }
      }
    }
    
    recursionStack.delete(nodeId);
    return false;
  }
  
  for (const dep of dependencies) {
    if (!visited.has(dep.id)) {
      dfs(dep.id, []);
    }
  }
  
  return cycles;
}

function calculateRiskScore(risk: Risk): string {
  const probMap = { low: 1, medium: 2, high: 3 };
  const prob = probMap[risk.probability];
  const impact = probMap[risk.impact];
  const score = prob * impact;
  
  if (score >= 6) return `🔴 CRITICAL (${score})`;
  if (score >= 4) return `🟡 HIGH (${score})`;
  if (score >= 2) return `🟢 MEDIUM (${score})`;
  return `⚪ LOW (${score})`;
}

function groupBy<T>(array: T[], key: keyof T): Record<string, T[]> {
  return array.reduce((result, item) => {
    const group = String(item[key]);
    if (!result[group]) {
      result[group] = [];
    }
    result[group].push(item);
    return result;
  }, {} as Record<string, T[]>);
}

