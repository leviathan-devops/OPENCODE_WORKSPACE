export function getDefaultPlanData(task: string): PlanData {
  return {
    task,
    requirements: [],
    constraints: [],
    dependencies: [],
    risks: [],
    checkpoints: [],
    steps: [],
  };
}

export function createCheckpoint(id: string, name: string, criteria: string[], time: string, owner: string = 'agent'): Checkpoint {
  return { id, name, criteria, time, owner };
}

export function createStep(
  id: string,
  name: string,
  description: string,
  time: string,
  criteria: string[],
  rollback: string,
  dependencies: string[] = [],
  owner: 'agent' | 'human' | 'system' = 'agent'
): Step {
  return { id, name, description, time, owner, criteria, rollback, dependencies };
}

export function createRisk(
  description: string,
  probability: 'low' | 'medium' | 'high',
  impact: 'low' | 'medium' | 'high',
  mitigation: string
): Risk {
  return { id: `RISK-${Date.now()}`, description, probability, impact, mitigation };
}

export function createDependency(
  id: string,
  name: string,
  type: 'file' | 'api' | 'service' | 'human',
  dependsOn: string[] = []
): Dependency {
  return { id, name, type, dependsOn };
}

export function createConstraint(
  type: 'time' | 'scope' | 'resource' | 'budget',
  value: string,
  hard: boolean = true
): Constraint {
  return { type, value, hard };
}
