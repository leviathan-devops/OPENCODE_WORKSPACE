function generateStandardPlan(data: PlanData): string {
  let output = '';
  
  output += `# Deep Plan: ${data.task}\n\n`;
  
  output += generateExecutiveSummary(data);
  output += '\n\n';
  
  output += generateRequirements(data.requirements);
  output += '\n\n';
  
  output += generateConstraints(data.constraints);
  output += '\n\n';
  
  output += generateDependencyGraph(data.dependencies);
  output += '\n\n';
  
  output += generateRiskRegister(data.risks);
  output += '\n\n';
  
  output += generateCheckpointTimeline(data.checkpoints);
  output += '\n\n';
  
  output += generateExecutionSteps(data.steps);
  
  output += '\n---\n*Generated by Deep Planning Mode v1.0*\n';
  
  return output;
}

function generateMinimalPlan(data: PlanData): string {
  let output = '';
  
  output += `# Plan: ${data.task}\n\n`;
  
  output += '## Steps\n\n';
  
  for (const step of data.steps) {
    output += `### ${step.id}: ${step.name} (~${step.time})\n`;
    output += `${step.description}\n\n`;
    output += '**Criteria:**\n';
    for (const criterion of step.criteria) {
      output += `- [ ] ${criterion}\n`;
    }
    output += '\n';
  }
  
  return output;
}

function generateDetailedPlan(data: PlanData): string {
  let output = '';
  
  output += `# Deep Plan: ${data.task}\n`;
  output += `*Generated: ${new Date().toISOString()}*\n\n`;
  
  output += generateExecutiveSummary(data);
  output += '\n\n';
  
  output += generateDetailedRequirements(data.requirements, data.constraints);
  output += '\n\n';
  
  output += generateConstraintAnalysis(data.constraints);
  output += '\n\n';
  
  output += generateDependencyGraph(data.dependencies);
  output += '\n\n';
  
  output += generateDetailedRiskRegister(data.risks);
  output += '\n\n';
  
  output += generateGanttTimeline(data.checkpoints);
  output += '\n\n';
  
  output += generateDetailedExecutionSteps(data.steps);
  output += '\n\n';
  
  output += generateSuccessMetrics(data);
  
  output += '\n---\n*Generated by Deep Planning Mode v1.0*\n';
  
  return output;
}

