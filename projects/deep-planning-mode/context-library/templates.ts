function generateExecutiveSummary(data: PlanData): string {
  let output = '## Executive Summary\n\n';
  
  output += `This plan addresses: **${data.task}**\n\n`;
  
  output += `**Key Deliverables:**\n`;
  for (const req of data.requirements.slice(0, 3)) {
    output += `- ${req}\n`;
  }
  if (data.requirements.length > 3) {
    output += `- ... and ${data.requirements.length - 3} more\n`;
  }
  output += '\n';
  
  output += `**Critical Risks:**\n`;
  const criticalRisks = data.risks.filter(r => r.impact === 'high' || r.probability === 'high');
  for (const risk of criticalRisks.slice(0, 3)) {
    output += `- ${risk.description} (${risk.probability}/${risk.impact})\n`;
  }
  if (criticalRisks.length === 0) {
    output += `- No critical risks identified\n`;
  }
  output += '\n';
  
  output += `**Timeline:** ${estimateTotalTime(data)} estimated\n`;
  output += `**Checkpoints:** ${data.checkpoints.length} milestones\n`;
  output += `**Execution Steps:** ${data.steps.length} steps\n`;
  
  return output;
}

function generateRequirements(requirements: string[]): string {
  let output = '## Requirements\n\n';
  
  output += '### Functional Requirements\n';
  for (const req of requirements) {
    output += `- ${req}\n`;
  }
  
  return output;
}

function generateDetailedRequirements(requirements: string[], constraints: Constraint[]): string {
  let output = '## Requirements\n\n';
  
  output += '### Functional Requirements\n';
  for (const req of requirements) {
    output += `- ${req}\n`;
  }
  
  output += '\n### Non-Functional Requirements\n';
  for (const constraint of constraints) {
    if (constraint.hard) {
      output += `- **[HARD]** ${constraint.type}: ${constraint.value}\n`;
    } else {
      output += `- ${constraint.type}: ${constraint.value}\n`;
    }
  }
  
  return output;
}

function generateConstraints(constraints: Constraint[]): string {
  let output = '## Constraints\n\n';
  
  for (const constraint of constraints) {
    const hard = constraint.hard ? ' **[HARD]**' : '';
    output += `- **${constraint.type}**: ${constraint.value}${hard}\n`;
  }
  
  return output;
}

function generateConstraintAnalysis(constraints: Constraint[]): string {
  let output = '## Constraints Analysis\n\n';
  
  const hardConstraints = constraints.filter(c => c.hard);
  const softConstraints = constraints.filter(c => !c.hard);
  
  output += '### Hard Constraints (Must Satisfy)\n';
  if (hardConstraints.length === 0) {
    output += '- None identified\n';
  } else {
    for (const c of hardConstraints) {
      output += `- \`${c.type}\`: ${c.value}\n`;
      output += `  - *Violation would block task completion*\n`;
    }
  }
  
  output += '\n### Soft Constraints (Desired)\n';
  if (softConstraints.length === 0) {
    output += '- None identified\n';
  } else {
    for (const c of softConstraints) {
      output += `- \`${c.type}\`: ${c.value}\n`;
      output += `  - *Can be relaxed if necessary*\n`;
    }
  }
  
  return output;
}

function generateDependencyGraph(dependencies: Dependency[]): string {
  let output = '## Dependency Graph\n\n';
  
  if (dependencies.length === 0) {
    return output + '*No dependencies identified*\n';
  }
  
  output += '```\n';
  
  // Detect circular dependencies
  const cycles = detectCycles(dependencies);
  if (cycles.length > 0) {
    output += '⚠️  CIRCULAR DEPENDENCIES DETECTED:\n';
    for (const cycle of cycles) {
      output += `  ${cycle.join(' → ')} → ${cycle[0]}\n`;
    }
    output += '\n';
  }
  
  // Build simple graph
  const nodes = new Set<string>();
  const edges: string[] = [];
  
  for (const dep of dependencies) {
    nodes.add(dep.id);
    for (const parent of dep.dependsOn) {
      nodes.add(parent);
      edges.push(`${parent} ──► ${dep.id}`);
    }
  }
  
  // Print nodes
  for (const node of nodes) {
    const dep = dependencies.find(d => d.id === node);
    if (dep) {
      output += `[${node}] ${dep.name} (${dep.type})\n`;
    } else {
      output += `[${node}]\n`;
    }
  }
  
  output += '\n';
  
  // Print edges
  for (const edge of edges) {
    output += `${edge}\n`;
  }
  
  output += '```\n';
  
  // List by type
  output += '\n### Dependencies by Type\n';
  
  const byType = groupBy(dependencies, 'type');
  for (const [type, deps] of Object.entries(byType)) {
    output += `\n**${type.toUpperCase()}**\n`;
    for (const dep of deps) {
      output += `- \`${dep.id}\`: ${dep.name}`;
      if (dep.dependsOn.length > 0) {
        output += ` (depends on: ${dep.dependsOn.join(', ')})`;
      }
      output += '\n';
    }
  }
  
  return output;
}

function generateRiskRegister(risks: Risk[]): string {
  let output = '## Risk Register\n\n';
  
  if (risks.length === 0) {
    return output + '*No risks identified*\n';
  }
  
  output += '| Risk | Probability | Impact | Mitigation |\n';
  output += '|------|-------------|--------|------------|\n';
  
  for (const risk of risks) {
    const color = risk.impact === 'high' ? '🔴' : risk.impact === 'medium' ? '🟡' : '🟢';
    output += `| ${color} ${risk.description} | ${risk.probability} | ${risk.impact} | ${risk.mitigation} |\n`;
  }
  
  return output;
}

function generateDetailedRiskRegister(risks: Risk[]): string {
  let output = '## Risk Register\n\n';
  
  if (risks.length === 0) {
    return output + '*No risks identified*\n';
  }
  
  output += '### High Priority Risks\n';
  const highRisks = risks.filter(r => r.impact === 'high' || r.probability === 'high');
  if (highRisks.length === 0) {
    output += '- None\n';
  } else {
    for (const risk of highRisks) {
      output += `\n**${risk.description}**\n`;
      output += `- Probability: ${risk.probability}\n`;
      output += `- Impact: ${risk.impact}\n`;
      output += `- Mitigation: ${risk.mitigation}\n`;
      output += `- Risk Score: ${calculateRiskScore(risk)}\n`;
    }
  }
  
  output += '\n### Medium Priority Risks\n';
  const mediumRisks = risks.filter(r => r.impact === 'medium' && r.probability === 'medium');
  if (mediumRisks.length === 0) {
    output += '- None\n';
  } else {
    for (const risk of mediumRisks) {
      output += `- ${risk.description} (${risk.mitigation})\n`;
    }
  }
  
  output += '\n### Low Priority Risks\n';
  const lowRisks = risks.filter(r => r.impact === 'low' && r.probability === 'low');
  if (lowRisks.length === 0) {
    output += '- None\n';
  } else {
    for (const risk of lowRisks) {
      output += `- ${risk.description}\n`;
    }
  }
  
  return output;
}

function generateCheckpointTimeline(checkpoints: Checkpoint[]): string {
  let output = '## Checkpoint Timeline\n\n';
  
  if (checkpoints.length === 0) {
    return output + '*No checkpoints defined*\n';
  }
  
  output += '| Checkpoint | Criteria | Time | Owner |\n';
  output += '|------------|----------|------|-------|\n';
  
  for (const cp of checkpoints) {
    const criteria = cp.criteria.slice(0, 2).join(', ');
    output += `| **${cp.id}**: ${cp.name} | ${criteria}${cp.criteria.length > 2 ? '...' : ''} | ${cp.time} | ${cp.owner} |\n`;
  }
  
  return output;
}

function generateGanttTimeline(checkpoints: Checkpoint[]): string {
  let output = '## Checkpoint Timeline (Gantt)\n\n';
  
  if (checkpoints.length === 0) {
    return output + '*No checkpoints defined*\n';
  }
  
  output += '```\n';
  
  let maxNameLen = 0;
  for (const cp of checkpoints) {
    maxNameLen = Math.max(maxNameLen, cp.name.length);
  }
  
  // Simplified Gantt
  for (const cp of checkpoints) {
    const name = cp.name.padEnd(maxNameLen);
    output += `${name} | ${cp.time}\n`;
  }
  
  output += '```\n';
  
  // Detailed view
  output += '\n### Checkpoint Details\n';
  
  for (const cp of checkpoints) {
    output += `\n#### ${cp.id}: ${cp.name}\n`;
    output += `- **Time**: ${cp.time}\n`;
    output += `- **Owner**: ${cp.owner}\n`;
    output += `- **Completion Criteria**:\n`;
    for (const criterion of cp.criteria) {
      output += `  - [ ] ${criterion}\n`;
    }
  }
  
  return output;
}

function generateExecutionSteps(steps: Step[]): string {
  let output = '## Execution Steps\n\n';
  
  if (steps.length === 0) {
    return output + '*No steps defined*\n';
  }
  
  for (const step of steps) {
    output += `### ${step.id}: ${step.name} (~${step.time})\n`;
    output += `\n**Owner:** ${step.owner}\n`;
    output += `\n${step.description}\n`;
    
    output += '\n**Completion Criteria:**\n';
    for (const criterion of step.criteria) {
      output += `- [ ] ${criterion}\n`;
    }
    
    output += '\n**Rollback:**\n';
    output += `${step.rollback}\n`;
    
    if (step.dependencies.length > 0) {
      output += '\n**Dependencies:**\n';
      for (const dep of step.dependencies) {
        output += `- Requires ${dep}\n`;
      }
    }
    
    output += '\n---\n\n';
  }
  
  return output;
}

function generateDetailedExecutionSteps(steps: Step[]): string {
  let output = '## Execution Steps\n\n';
  
  if (steps.length === 0) {
    return output + '*No steps defined*\n';
  }
  
  output += `Total: ${steps.length} steps\n\n`;
  
  for (const step of steps) {
    output += `### ${step.id}: ${step.name}\n`;
    output += `\n| Attribute | Value |\n`;
    output += `|-----------|-------|\n`;
    output += `| Estimated Time | ${step.time} |\n`;
    output += `| Owner | ${step.owner} |\n`;
    output += `| Dependencies | ${step.dependencies.join(', ') || 'None'} |\n`;
    
    output += '\n**Description:**\n';
    output += `${step.description}\n`;
    
    output += '\n**Success Criteria:**\n';
    for (const criterion of step.criteria) {
      output += `- [ ] ${criterion}\n`;
    }
    
    output += '\n**Rollback Procedure:**\n';
    output += `${step.rollback}\n`;
    
    output += '\n---\n\n';
  }
  
  return output;
}

function generateSuccessMetrics(data: PlanData): string {
  let output = '## Success Metrics\n\n';
  
  output += '### Plan Completeness\n';
  output += `- Requirements defined: ${data.requirements.length}\n`;
  output += `- Dependencies mapped: ${data.dependencies.length}\n`;
  output += `- Risks identified: ${data.risks.length}\n`;
  output += `- Checkpoints: ${data.checkpoints.length}\n`;
  output += `- Execution steps: ${data.steps.length}\n`;
  
  output += '\n### Validation Checklist\n';
  output += '- [ ] All requirements have acceptance criteria\n';
  output += '- [ ] No circular dependencies (or explicitly accepted)\n';
  output += '- [ ] All high-impact risks have mitigations\n';
  output += '- [ ] Each checkpoint has measurable criteria\n';
  output += '- [ ] Each step has rollback procedure\n';
  output += '- [ ] Total time within constraints\n';
  
  return output;
}

